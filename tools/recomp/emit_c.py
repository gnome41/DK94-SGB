"""C code generation for the fallback interpreter and recompiled functions.

Both generators take instruction semantics from sm83.py and must keep the
same ordering of memory accesses, TICK() and interrupt checks, so that a
recompiled run is cycle-for-cycle identical to an interpreted one (this is
what the --interp hash comparison test relies on)."""

import sm83


def fill(template, n8, n16, e8):
    return template.replace("{n8}", n8).replace("{n16}", n16).replace("{e8}", e8)


# ---------------------------------------------------------------- interpreter

def interp_body(op, length):
    """C statements for one opcode in the interpreter (pc = its address)."""
    k = op.kind
    nxt = f"(uint16_t)(pc + {length})"
    cond = op.cond
    if k == "op":
        code = fill(op.code, "n8", "n16", "(int8_t)n8")
        return f"R.pc = {nxt}; {code} TICK({op.cycles});"
    if k in ("jp", "jr"):
        tgt = "n16" if k == "jp" else f"(uint16_t)(pc + 2 + (int8_t)n8)"
        if cond:
            return (f"if ({cond}) {{ R.pc = {tgt}; TICK({op.cycles_taken}); }} "
                    f"else {{ R.pc = {nxt}; TICK({op.cycles}); }}")
        return f"R.pc = {tgt}; TICK({op.cycles});"
    if k == "call":
        if cond:
            return (f"if ({cond}) {{ push16({nxt}); R.pc = n16; TICK({op.cycles_taken}); }} "
                    f"else {{ R.pc = {nxt}; TICK({op.cycles}); }}")
        return f"push16({nxt}); R.pc = n16; TICK({op.cycles});"
    if k == "ret":
        if cond:
            return (f"if ({cond}) {{ R.pc = pop16(); TICK({op.cycles_taken}); }} "
                    f"else {{ R.pc = {nxt}; TICK({op.cycles}); }}")
        return f"R.pc = pop16(); TICK({op.cycles});"
    if k == "reti":
        return f"R.pc = pop16(); R.ime = 1; TICK({op.cycles});"
    if k == "rst":
        return f"push16({nxt}); R.pc = {op.target:#06x}; TICK({op.cycles});"
    if k == "jphl":
        return f"R.pc = HL; TICK({op.cycles});"
    if k == "halt":
        return f"R.pc = {nxt}; TICK({op.cycles}); gb_halt();"
    if k == "stop":
        return f"R.pc = {nxt}; TICK({op.cycles}); gb_stop();"
    if k == "di":
        return f"R.pc = {nxt}; R.ime = 0; R.ei_delay = 0; TICK({op.cycles});"
    if k == "ei":
        return f"R.pc = {nxt}; if (!R.ime) {{ R.ei_delay = 1; }} TICK({op.cycles});"
    if k == "illegal":
        return "gb_illegal(pc);"
    raise ValueError(k)


def gen_interp():
    out = ["/* generated by tools/recomp - do not edit */", "switch (op) {"]
    for o in range(256):
        if o == 0xCB:
            out.append("case 0xCB: {")
            out.append("    uint8_t cb = RD(pc + 1);")
            out.append("    switch (cb) {")
            for c in range(256):
                out.append(f"    case {c:#04x}: {{ {interp_body(sm83.CB[c], 2)} }} return;")
            out.append("    }")
            out.append("    return;")
            out.append("}")
            continue
        op = sm83.MAIN[o]
        pre = ""
        if op.length == 2:
            pre = "uint8_t n8 = RD(pc + 1); (void)n8; "
        if op.length == 3:
            pre = "uint16_t n16 = RD(pc + 1) | (RD(pc + 2) << 8); "
        out.append(f"case {o:#04x}: {{ {pre}{interp_body(op, op.length)} }} return;")
    out.append("}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------- recompiled code

def label(addr):
    return f"L_{addr:04X}"


def compiled_insn(insn, bank, body):
    """C for one instruction.  body = set of addresses in this function."""
    op = insn.op
    k = op.kind
    a = insn.addr
    nxt = insn.next
    lines = [f"{label(a)}: /* {insn.text()} */"]
    lines.append(f"    IRQB({a:#06x}, {bank});" if a >= 0x4000 else f"    IRQ({a:#06x});")

    def go(t):
        return f"goto {label(t)};" if t in body else f"EXIT({t:#06x});"

    cond = op.cond
    e8 = str(insn.e8)
    if k == "op":
        code = fill(op.code, f"{insn.n8:#04x}", f"{insn.n16:#06x}", e8)
        lines.append(f"    {code} TICK({op.cycles});" if code else f"    TICK({op.cycles});")
    elif k in ("jp", "jr"):
        t = insn.jump_target
        if cond:
            lines.append(f"    if ({cond}) {{ TICK({op.cycles_taken}); {go(t)} }}")
            lines.append(f"    TICK({op.cycles});")
        else:
            lines.append(f"    TICK({op.cycles}); {go(t)}")
            return lines, False
    elif k == "call":
        t = insn.jump_target
        if cond:
            lines.append(f"    if ({cond}) {{ push16({nxt:#06x}); TICK({op.cycles_taken}); EXIT({t:#06x}); }}")
            lines.append(f"    TICK({op.cycles});")
        else:
            lines.append(f"    push16({nxt:#06x}); TICK({op.cycles}); EXIT({t:#06x});")
            return lines, False
    elif k == "rst":
        lines.append(f"    push16({nxt:#06x}); TICK({op.cycles}); EXIT({op.target:#06x});")
        return lines, False
    elif k == "ret":
        if cond:
            lines.append(f"    if ({cond}) {{ uint16_t t = pop16(); TICK({op.cycles_taken}); EXIT(t); }}")
            lines.append(f"    TICK({op.cycles});")
        else:
            lines.append(f"    {{ uint16_t t = pop16(); TICK({op.cycles}); EXIT(t); }}")
            return lines, False
    elif k == "reti":
        lines.append(f"    {{ uint16_t t = pop16(); R.ime = 1; TICK({op.cycles}); EXIT(t); }}")
        return lines, False
    elif k == "jphl":
        lines.append(f"    TICK({op.cycles}); EXIT(HL);")
        return lines, False
    elif k == "halt":
        lines.append(f"    TICK({op.cycles}); gb_halt();")
    elif k == "stop":
        lines.append(f"    TICK({op.cycles}); gb_stop();")
    elif k == "di":
        lines.append(f"    R.ime = 0; R.ei_delay = 0; TICK({op.cycles});")
    elif k == "ei":
        lines.append(f"    if (!R.ime) {{ R.ei_delay = 1; }} TICK({op.cycles});")
    elif k == "illegal":
        lines.append(f"    R.pc = {a:#06x}; gb_illegal({a:#06x}); return;")
        return lines, False
    else:
        raise ValueError(k)
    return lines, True  # falls through to insn.next


def fn_name(bank, entry):
    return f"f_{bank:02X}_{entry:04X}"


def gen_function(fn):
    """fn: analyze.Function.  Returns C source text."""
    body = {i.addr for i in fn.insns}
    out = [f"void {fn_name(fn.bank, fn.entry)}(void)", "{", "    switch (R.pc) {"]
    for i in fn.insns:
        out.append(f"    case {i.addr:#06x}: goto {label(i.addr)};")
    out.append("    default: return;")
    out.append("    }")
    insns = fn.insns
    for idx, insn in enumerate(insns):
        lines, falls = compiled_insn(insn, fn.bank, body)
        out.extend(lines)
        if falls:
            nxt = insn.next
            following = insns[idx + 1].addr if idx + 1 < len(insns) else None
            if following != nxt:
                out.append(f"    {'goto ' + label(nxt) + ';' if nxt in body else f'EXIT({nxt:#06x});'}")
    out.append("}")
    return "\n".join(out) + "\n"
