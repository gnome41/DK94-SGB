#!/usr/bin/env python3
"""Static recompiler: Game Boy ROM -> C.

usage: recomp.py --rom ROM --out DIR [--config overrides.toml] [--coverage FILE ...]
       recomp.py --interp-only --out DIR
"""

import argparse
import os
import sys
import tomllib
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import analyze  # noqa: E402
import emit_c   # noqa: E402

HEADER = '/* generated by tools/recomp - do not edit */\n#include "cpu_ops.h"\n\n'


def write_if_changed(path, text):
    try:
        with open(path) as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w") as f:
        f.write(text)


def read_coverage(paths):
    refs = []
    for p in paths:
        if not os.path.exists(p):
            continue
        with open(p) as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#"):
                    refs.append(analyze.parse_ref(line))
    return refs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rom")
    ap.add_argument("--out", required=True)
    ap.add_argument("--config")
    ap.add_argument("--coverage", nargs="*", default=[])
    ap.add_argument("--banks", type=int, help="number of bank files to emit (default: from ROM)")
    ap.add_argument("--interp-only", action="store_true")
    args = ap.parse_args()

    os.makedirs(args.out, exist_ok=True)
    write_if_changed(os.path.join(args.out, "interp_ops.inc"), emit_c.gen_interp())
    if args.interp_only:
        return

    with open(args.rom, "rb") as f:
        data = f.read()
    cfg = {}
    if args.config:
        with open(args.config, "rb") as f:
            cfg = tomllib.load(f)

    rom = analyze.Rom(data)
    an = analyze.Analyzer(rom, cfg)
    seeds = [(0, 0x0100)] + [(0, v) for v in range(0, 0x68, 8)]
    seeds += [analyze.parse_ref(e) for e in cfg.get("entries", [])]
    an.run(seeds)

    # Coverage from the runtime's fallback log: anything the interpreter
    # executed that static analysis missed becomes a new entry point.
    cov = read_coverage(args.coverage)
    added = 0
    for ref in sorted(set(cov)):
        if ref not in an.insns:
            an.add_entry(*ref)
            an.run([])
            added += 1

    funcs = an.functions()
    nbanks = args.banks or rom.banks
    by_bank = {b: [] for b in range(nbanks)}
    for fn in funcs:
        by_bank.setdefault(fn.bank, []).append(fn)

    entries = []
    for b in range(nbanks):
        parts = [HEADER]
        for fn in by_bank.get(b, []):
            parts.append(emit_c.gen_function(fn))
            parts.append("\n")
            for i in fn.insns:
                entries.append((fn.bank, i.addr, emit_c.fn_name(fn.bank, fn.entry), i.addr == fn.entry))
        write_if_changed(os.path.join(args.out, f"gen_bank_{b:02d}.c"), "".join(parts))

    # Entry points first so that a function is preferred for its own entry.
    entries.sort(key=lambda e: (not e[3], e[0], e[1]))
    t = [HEADER]
    for fn in funcs:
        t.append(f"void {emit_c.fn_name(fn.bank, fn.entry)}(void);\n")
    t.append(f"\nconst uint32_t gen_rom_crc32 = {zlib.crc32(data):#010x}u;\n")
    t.append("const GenEntry gen_entries[] = {\n")
    for bank, addr, name, _ in entries:
        t.append(f"    {{ {bank}, {addr:#06x}, {name} }},\n")
    if not entries:
        t.append("    { 0, 0, 0 },\n")
    t.append("};\n")
    t.append(f"const size_t gen_entry_count = {len(entries)};\n")
    write_if_changed(os.path.join(args.out, "gen_table.c"), "".join(t))

    # report
    covered = {}
    for (b, a), insn in an.insns.items():
        covered[b] = covered.get(b, 0) + insn.length
    print(f"recomp: {len(funcs)} functions, {len(an.insns)} instructions, "
          f"{len(an.tables)} jump tables, {added} coverage seeds added")
    for b in sorted(covered):
        print(f"  bank {b:02X}: {len(by_bank.get(b, []))} functions, {covered[b]} code bytes")


if __name__ == "__main__":
    main()
